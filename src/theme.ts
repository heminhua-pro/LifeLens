import { reactive, watch } from 'vue'

/* ---------- 主题状态：light = 极光渐变风(B)，dark = 暗夜玻璃拟态(A) ---------- */

export type UIMode = 'light' | 'dark'
export type UILang = 'zh' | 'en'

function load<T>(key: string, fallback: T): T {
  try {
    const v = localStorage.getItem(key)
    return (v === 'dark' || v === 'light' || v === 'zh' || v === 'en') ? (v as unknown as T) : fallback
  } catch { return fallback }
}

export const ui = reactive({
  mode: load<UIMode>('lifelens_mode', 'light'),
  lang: load<UILang>('lifelens_lang', 'zh')
})

function applyMode(m: UIMode) {
  document.documentElement.dataset.theme = m
  try { localStorage.setItem('lifelens_mode', m) } catch { /* ignore */ }
}
watch(() => ui.mode, applyMode)
applyMode(ui.mode)

watch(() => ui.lang, l => {
  try { localStorage.setItem('lifelens_lang', l) } catch { /* ignore */ }
})

export function toggleMode() {
  ui.mode = ui.mode === 'dark' ? 'light' : 'dark'
}
export function toggleLang() {
  ui.lang = ui.lang === 'zh' ? 'en' : 'zh'
}

